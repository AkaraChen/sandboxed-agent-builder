// Paths inside the image (runtime contract 1).
const (
	// ImageRoot holds each plugin at ImageRoot/<name> (PLUGIN_ROOT).
	ImageRoot = "/opt/agent/plugins"
	// DataRoot holds each plugin's writable PLUGIN_DATA directory; mount a
	// volume here to keep it across image updates.
	DataRoot = "/var/lib/agent-plugins"
	// CodexSystemDir is Codex's system configuration: config.toml,
	// requirements.toml (managed hooks) and skills.
	CodexSystemDir = "/etc/codex"
	// SkillsDir is where Codex discovers admin-scoped skills.
	SkillsDir = "/etc/codex/skills"
	// HooksConfig is the plugins' merged akhook rules, read through
	// AKHOOK_ADDITIONAL_CONFIG_PATH.
	HooksConfig = "/etc/akhook/plugins.yml"
)

var serverIDRE = regexp.MustCompile(`[^A-Za-z0-9_-]`)

// ServerID is a plugin server's name in Codex: <plugin>_<server>.
func ServerID(plugin, server string) string {
	return serverIDRE.ReplaceAllString(plugin+"_"+server, "_")
}

// SkillDest is where a plugin's skill directory goes in the image; the
// plugin name prefix keeps plugins' directories apart.
func SkillDest(plugin string, s Skill) string {
	return SkillsDir + "/" + plugin + "--" + s.Dir
}

// codexBase is the system configuration every image gets. The container is
// the isolation boundary, so Codex runs without its own sandbox inside it
// (its Linux sandbox needs privileges a container does not have).
const codexBase = `# Generated by sandboxed-agent-builder (runtime contract 1).
# System-wide Codex configuration. Model, instructions and credentials come
# from the caller when it runs the image.
sandbox_mode = "danger-full-access"
`

// CodexConfig is /etc/codex/config.toml for the plugins: the base settings
// and every plugin MCP server, with tools approved (nobody answers approval
// requests inside a driven session).
func CodexConfig(list []*Plugin) (string, error) {
	servers := map[string]any{}
	for _, p := range list {
		names := make([]string, 0, len(p.Servers))
		for n := range p.Servers {
			names = append(names, n)
		}
		sort.Strings(names)
		for _, n := range names {
			id := ServerID(p.Name, n)
			if _, dup := servers[id]; dup {
				return "", fmt.Errorf("MCP server id %s is used twice", id)
			}
			servers[id] = codexServer(p, n, p.Servers[n])
		}
	}
	var b strings.Builder
	b.WriteString(codexBase)
	if len(servers) > 0 {
		out, err := toml.Marshal(map[string]any{"mcp_servers": servers})
		if err != nil {
			return "", err
		}
		b.WriteString("\n# The plugins' MCP servers.\n")
		b.Write(out)
	}
	return b.String(), nil
}

// expand replaces the specification's placeholders with the plugin's
// directories in the image.
func expand(s, root, data string) string {
	return strings.NewReplacer(Root, root, Data, data).Replace(s)
}

var tokenEnvRE = regexp.MustCompile(`[^A-Z0-9_]`)

// TokenEnv is the environment variable holding the bearer token for a
// plugin's streamable-http server. Agent Plugins leaves authorization to
// the client; this image's way is a token the caller supplies at run time.
func TokenEnv(plugin, server string) string {
	return "MCP_TOKEN_" + tokenEnvRE.ReplaceAllString(strings.ToUpper(plugin+"_"+server), "_")
}

// RuntimeEnv lists the variables a plugin reads at run time.
func RuntimeEnv(p *Plugin) []string {
	var out []string
	for name, s := range p.Servers {
		if s.Type == "streamable-http" {
			out = append(out, TokenEnv(p.Name, name))
		}
	}
	sort.Strings(out)
	return out
}

// codexServer is a server of plugin p in Codex's mcp_servers table.
func codexServer(p *Plugin, name string, s Server) map[string]any {
	root, data := ImageRoot+"/"+p.Name, DataRoot+"/"+p.Name
	out := map[string]any{"default_tools_approval_mode": "approve"}
	if s.Type == "streamable-http" {
		out["url"] = s.URL
		out["bearer_token_env_var"] = TokenEnv(p.Name, name)
		if len(s.Headers) > 0 {
			out["http_headers"] = s.Headers
		}
		return out
	}
	command := s.Command
	if rel, ok := strings.CutPrefix(command, "./"); ok {
		command = root + "/" + rel
	}
	out["command"] = command
	if len(s.Args) > 0 {
		args := make([]string, len(s.Args))
		for i, a := range s.Args {
			args[i] = expand(a, root, data)
		}
		out["args"] = args
	}
	cwd := root
	switch {
	case strings.HasPrefix(s.Cwd, "./"):
		cwd = root + "/" + s.Cwd[2:]
	case s.Cwd != "":
		cwd = expand(s.Cwd, root, data)
	}
	out["cwd"] = cwd
	env := map[string]string{}
	for k, v := range s.Env {
		env[k] = expand(v, root, data)
	}
	env["PLUGIN_ROOT"], env["PLUGIN_DATA"] = root, data
	out["env"] = env
	return out
}

// CodexRequirements is /etc/codex/requirements.toml: akhook as Codex's
// only hooks, managed (trusted by policy). Hooks from any other source,
// including ones the agent writes, never run. No matcher on PreToolUse:
// akhook gets every tool call that goes through Codex's hook path.
const CodexRequirements = `# Generated by sandboxed-agent-builder (runtime contract 1).
# akhook runs the plugins' hooks (AKHOOK_ADDITIONAL_CONFIG_PATH); it holds
# the Codex hook adapter, the builder only registers it.
allow_managed_hooks_only = true

[[hooks.PreToolUse]]
[[hooks.PreToolUse.hooks]]
type = "command"
command = "akhook codex hook pre_tool_use"
timeout = 30

[[hooks.UserPromptSubmit]]
[[hooks.UserPromptSubmit.hooks]]
type = "command"
command = "akhook codex hook prompt_submit"
timeout = 30

[[hooks.Stop]]
[[hooks.Stop.hooks]]
type = "command"
command = "akhook codex hook stop"
timeout = 30
`

// HooksYAML merges the plugins' akhook rules into one config: rule ids get
// their plugin's name (memory/recall) and ${PLUGIN_ROOT} becomes the
// plugin's directory in the image.
func HooksYAML(list []*Plugin) (string, error) {
	rules := []any{}
	for _, p := range list {
		root := ImageRoot + "/" + p.Name
		for _, r := range p.Hooks {
			rule := expandAny(r, root, DataRoot+"/"+p.Name).(map[string]any)
			rule["id"] = p.Name + "/" + rule["id"].(string)
			rules = append(rules, rule)
		}
	}
	out, err := yaml.Marshal(map[string]any{"version": 1, "rules": rules})
	if err != nil {
		return "", err
	}
	return "# Generated by sandboxed-agent-builder: the plugins' akhook rules.\n" + string(out), nil
}

func expandAny(v any, root, data string) any {
	switch t := v.(type) {
	case string:
		return expand(t, root, data)
	case []any:
		out := make([]any, len(t))
		for i, x := range t {
			out[i] = expandAny(x, root, data)
		}
		return out
	case map[string]any:
		out := make(map[string]any, len(t))
		for k, x := range t {
			out[k] = expandAny(x, root, data)
		}
		return out
	}
	return v
}

// HookEvents lists the Codex events a plugin's hooks run on, for metadata.
func HookEvents(p *Plugin) []string {
	var out []string
	for _, r := range p.Hooks {
		out = append(out, fmt.Sprintf("%s:%v", r["id"], r["on"]))
	}
	return out
}
